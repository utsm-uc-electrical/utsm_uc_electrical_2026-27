/* PA8 debounce is independent of CAN transport and the peer LED state. */
static void ProcessInput(void)
{
  uint32_t now = HAL_GetTick();
  rawInputState = (HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_8) == GPIO_PIN_SET) ? 1U : 0U;
  if (rawInputState != inputCandidate)
  {
    inputCandidate = rawInputState;
    inputCandidateTick = now;
  }
  if ((localInputState != inputCandidate) &&
      ((uint32_t)(now - inputCandidateTick) >= INPUT_DEBOUNCE_MS))
  {
    localInputState = inputCandidate;
  }
}
